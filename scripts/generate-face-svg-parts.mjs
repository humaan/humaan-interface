import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "src/assets/face-parts");
const outputPath = path.join(root, "src/domain/face/svgParts.generated.ts");
const directoryPrefixes = {
	eyes: "Eye",
	mouth: "Mouth",
	nose: "Nose",
	"nose-eye": "NoseEye",
};

const entries = [];

for (const [directory, prefix] of Object.entries(directoryPrefixes)) {
	const filenames = (await readdir(path.join(sourceRoot, directory)))
		.filter(filename => filename.endsWith(".svg"))
		.sort();

	for (const filename of filenames) {
		const source = await readFile(path.join(sourceRoot, directory, filename), "utf8");
		const viewBox = source.match(/viewBox=["']([^"']+)["']/i)?.[1];
		const content = source.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i)?.[1]?.trim();
		if (!viewBox || !content) throw new Error(`Could not parse ${directory}/${filename}`);

		const number = path.basename(filename, ".svg").padStart(2, "0");
		entries.push([
			`${prefix}${number}`,
			{
				viewBox,
				content: content
					.replace(/fill=["'](?:#000(?:000)?|black)["']/gi, 'fill="currentColor"')
					.replace(/\r?\n/g, " ")
					.replace(/\s{2,}/g, " "),
			},
		]);
	}
}

const output = `/* This file is generated by scripts/generate-face-svg-parts.mjs. */
import type { FacePartName } from "./parts";

type FacePartSvgSource = {
\tviewBox: string;
\tcontent: string;
};

export const facePartSvgSources = ${JSON.stringify(Object.fromEntries(entries), null, "\t")} as const satisfies Record<FacePartName, FacePartSvgSource>;
`;

await writeFile(outputPath, output);
console.log(`Generated ${path.relative(root, outputPath)} with ${entries.length} face parts.`);
